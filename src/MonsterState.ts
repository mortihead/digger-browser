/** Изменяемое состояние одного монстра. Порт org.digger.app.MonsterState. */
export class MonsterState {
  x = 0;
  y = 0; // пиксельная позиция
  h = 0;
  v = 0; // позиция в ячейках
  xr = 0;
  yr = 0; // субпиксельный остаток внутри ячейки
  direction = 0; // текущее направление движения
  horizontalDir = 0; // предпочтительное горизонтальное направление
  type = 0; // таймер/индикатор поведения монстра
  huntTime = 0; // таймер режима погони
  death = 0; // стадия анимации смерти (0 = жив)
  bag = 0; // мешок, убивший монстра
  deathTime = 0; // кадров с момента смерти
  spawnTime = 0; // счётчик задержки появления
  flag = false; // общий флаг (появился/активен)
  nob = false; // не может сменить направление в этом кадре
  alive = false; // монстр жив и виден
}
